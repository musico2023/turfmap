#!/usr/bin/env node
/**
 * Build the TurfMap Shorby banner SVG (and 1x + 2x PNGs).
 *
 * Wordmark uses the EXACT font instance the live site serves —
 * "Bricolage Grotesque 96pt ExtraBold" — pulled from turfmap.ai's
 * next/font preload (a static cut of the variable Bricolage at
 * opsz=96, wght=800). next/font picks this instance for the
 * `font-display font-bold` Tailwind chain in MarketingNav, so this
 * is literally what visitors see in the nav lockup.
 *
 * Font is embedded as a base64 data URI in the SVG so the PNG
 * rendering reproduces it without relying on system font availability.
 *
 * Right half: the homepage hero PATTERN from
 * components/marketing/heroSeed.ts rendered with the canonical
 * rank colors from components/turfmap/HeatmapGrid.tsx. No numeric
 * labels — banner-grade visual, color-coded only.
 *
 * Re-run after any pattern/color/wordmark changes.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import sharp from 'sharp';

const ROOT = resolve(import.meta.dirname, '..');
const FONT_PATH = '/tmp/livefonts/bricolage-96pt-extrabold.ttf';
const OUT_SVG = resolve(ROOT, 'public/brand/turfmap-shorby.svg');
const OUT_PNG_1X = resolve(ROOT, 'public/brand/turfmap-shorby.png');
const OUT_PNG_2X = resolve(ROOT, 'public/brand/turfmap-shorby@2x.png');

// Convert wordmark glyphs to SVG paths via a Python helper that uses
// fontTools (handles modern OpenType features opentype.js chokes on).
// (Embedding the TTF as @font-face data URI didn't work — sharp's
// underlying renderer doesn't honor @font-face from inline <style>,
// so the wordmark fell back to a serif system font. Converting text
// → <path/> bypasses font matching entirely.)
const FONT_HELPER = resolve(import.meta.dirname, '_font_to_svg_path.py');

function renderText(text, fontSize, trackingEm = -0.03) {
  const out = execFileSync(
    'python3',
    [FONT_HELPER, FONT_PATH, text, String(fontSize), String(trackingEm)],
    { encoding: 'utf8' }
  );
  return JSON.parse(out);
}

/** Render `text` as glyph outlines positioned at (x, y) baseline. */
function textToPath(text, x, y, fontSize, fill) {
  const { glyphs_svg } = renderText(text, fontSize);
  return `<g transform="translate(${x}, ${y})" fill="${fill}">${glyphs_svg}</g>`;
}

/** Measure rendered text width so subsequent elements can flow flush. */
function textWidth(text, fontSize) {
  return renderText(text, fontSize).width;
}

// ── Brand constants (mirror heroSeed.ts + HeatmapGrid.tsx) ────────

const PATTERN = [
  '.........',
  '..3.3....',
  '.3.232.3.',
  '..32123..',
  '..21112..',
  '..32123..',
  '.3.232.3.',
  '..3.3....',
  '.........',
];

const COLORS = {
  '1': '#c5ff3a',
  '2': '#e8e54a',
  '3': '#ff9f3a',
  '.': '#ff4d4d',
};

// ── Geometry ────────────────────────────────────────────────────────

const WIDTH = 1200;
const HEIGHT = 500;
const CELL = 32;
const GAP = 4;
const GRID_SIZE = 9 * CELL + 8 * GAP; // 288 + 32 = 320
const GRID_X = WIDTH - GRID_SIZE - 80;
const GRID_Y = Math.round((HEIGHT - GRID_SIZE) / 2); // 90

// ── Heatmap cells (no labels — banner-grade visual) ────────────────

function buildCells() {
  const out = [];
  for (let y = 0; y < 9; y++) {
    const row = PATTERN[y];
    for (let x = 0; x < 9; x++) {
      const ch = row[x] ?? '.';
      const cx = GRID_X + x * (CELL + GAP);
      const cy = GRID_Y + y * (CELL + GAP);
      const fill = COLORS[ch];
      out.push(`    <rect x="${cx}" y="${cy}" width="${CELL}" height="${CELL}" rx="5" fill="${fill}"/>`);
    }
  }
  return out.join('\n');
}

// ── SVG template — wordmark mirrors public/brand/turfmap-logo.svg ──

const svg = `<svg width="${WIDTH}" height="${HEIGHT}" viewBox="0 0 ${WIDTH} ${HEIGHT}" xmlns="http://www.w3.org/2000/svg">
  <!--
    TurfMap Shorby banner — ${WIDTH}×${HEIGHT}.
    Auto-generated by scripts/generate-shorby-banner.mjs.
    DO NOT edit by hand — re-run the script.

    Wordmark uses the EXACT live-site font: Bricolage Grotesque
    96pt ExtraBold (embedded as base64 below). "TurfMap" + lime ™
    superscript, lime crosshair icon square. Heatmap uses the
    homepage hero PATTERN with the four canonical rank colors but
    renders cells WITHOUT numeric labels for a cleaner banner visual.
  -->
  <defs>
    <linearGradient id="bg-grad" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="#0d0d10"/>
      <stop offset="100%" stop-color="#070708"/>
    </linearGradient>
    <radialGradient id="lime-glow" cx="22%" cy="38%" r="55%">
      <stop offset="0%" stop-color="#c5ff3a" stop-opacity="0.08"/>
      <stop offset="60%" stop-color="#c5ff3a" stop-opacity="0.02"/>
      <stop offset="100%" stop-color="#c5ff3a" stop-opacity="0"/>
    </radialGradient>
  </defs>

  <!-- Background -->
  <rect width="${WIDTH}" height="${HEIGHT}" fill="url(#bg-grad)"/>
  <rect width="${WIDTH}" height="${HEIGHT}" fill="url(#lime-glow)"/>
  <rect x="0.5" y="0.5" width="${WIDTH - 1}" height="${HEIGHT - 1}" fill="none" stroke="#27272a" stroke-width="1"/>

  <!-- ── LEFT: brand lockup (mirrors turfmap-logo.svg) ─────────── -->

  <!-- Lime icon square — same crosshair construction as turfmap-logo.svg -->
  <g transform="translate(80, 190)">
    <rect width="120" height="120" rx="22" fill="#c5ff3a"/>
    <circle cx="60" cy="60" r="28" fill="#000"/>
    <circle cx="60" cy="60" r="22" fill="#c5ff3a"/>
    <rect x="56.5" y="22" width="7"  height="14" rx="3.5" fill="#000"/>
    <rect x="56.5" y="84" width="7"  height="14" rx="3.5" fill="#000"/>
    <rect x="22"   y="56.5" width="14" height="7" rx="3.5" fill="#000"/>
    <rect x="84"   y="56.5" width="14" height="7" rx="3.5" fill="#000"/>
    <circle cx="60" cy="60" r="4" fill="#000"/>
  </g>

  <!-- Wordmark — "TurfMap" rendered as a glyph outline path from
       Bricolage Grotesque 96pt ExtraBold (the exact font next/font
       serves on turfmap.ai). Embedded as <path> so the PNG render
       doesn't depend on font matching in sharp's renderer. -->
  ${textToPath('TurfMap', 230, 278, 100, '#fafafa')}
  <!-- Lime ™ superscript, also as a path -->
  ${textToPath('™', 230 + textWidth('TurfMap', 100) + 6, 208, 30, '#c5ff3a')}

  <!-- ── RIGHT: 9×9 heatmap (homepage PATTERN, colors only) ───── -->
  <g>
${buildCells()}
  </g>

  <!-- ── Bottom-right tagline (also a glyph path) ─────────────── -->
  ${(() => {
    const tag = 'GOOGLE MAPS AUDIT TOOL';
    const tagSize = 20;
    const tw = textWidth(tag, tagSize);
    return textToPath(tag, WIDTH - 80 - tw, HEIGHT - 45, tagSize, '#c5ff3a');
  })()}
</svg>
`;

writeFileSync(OUT_SVG, svg);
console.log(`✓ wrote ${OUT_SVG} (${svg.length} bytes)`);

// ── PNG export at 1x and 2x ────────────────────────────────────────

const svgBuf = Buffer.from(svg, 'utf8');

await sharp(svgBuf, { density: 144 })
  .resize(WIDTH, HEIGHT)
  .png()
  .toFile(OUT_PNG_1X);
const info1x = await sharp(OUT_PNG_1X).metadata();
console.log(`✓ wrote ${OUT_PNG_1X} (${info1x.width}×${info1x.height})`);

await sharp(svgBuf, { density: 288 })
  .resize(WIDTH * 2, HEIGHT * 2)
  .png()
  .toFile(OUT_PNG_2X);
const info2x = await sharp(OUT_PNG_2X).metadata();
console.log(`✓ wrote ${OUT_PNG_2X} (${info2x.width}×${info2x.height})`);
