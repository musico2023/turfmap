#!/usr/bin/env node
/**
 * Build the TurfMap Shorby banner SVG (and 1x + 2x PNGs).
 *
 * - Embeds the Bricolage Grotesque Bold font as a base64 @font-face
 *   so the rendered PNG matches the live site wordmark (the brand
 *   uses font-display = Bricolage Grotesque via next/font/google).
 * - Uses the EXACT 9×9 hero pattern from components/marketing/heroSeed.ts
 *   so the visual on the banner mirrors what visitors see on the
 *   homepage.
 * - Uses the canonical cell colors from components/turfmap/HeatmapGrid.tsx
 *   (#1 lime, #2 yellow, #3 orange, not-in-pack red).
 *
 * Re-run after any pattern/color changes to refresh the static assets.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import sharp from 'sharp';

const ROOT = resolve(import.meta.dirname, '..');
const FONT_PATH = '/tmp/bricolage/BricolageGrotesque-Bold.ttf';
const OUT_SVG = resolve(ROOT, 'public/brand/turfmap-shorby.svg');
const OUT_PNG_1X = resolve(ROOT, 'public/brand/turfmap-shorby.png');
const OUT_PNG_2X = resolve(ROOT, 'public/brand/turfmap-shorby@2x.png');

// ── Brand constants (mirror lib/turfmap colors + heroSeed pattern) ──

// Hero PATTERN, copied verbatim from components/marketing/heroSeed.ts.
// Read row-by-row, y=0 top → y=8 bottom. '1' '2' '3' = rank, '.' = not
// in 3-pack. The home page heatmap visualizes this exact data.
const PATTERN = [
  '.........',
  '..3.3....',
  '.3.232.3.',
  '..32123..',
  '..21112..',
  '..32123..',
  '.3.232.3.',
  '..3.3....',
  '.........',
];

// Cell colors, copied verbatim from components/turfmap/HeatmapGrid.tsx's
// rankColor() function so the banner uses the same palette the live
// dashboard does.
const COLORS = {
  '1': '#c5ff3a', // brand lime — #1 in the 3-pack
  '2': '#e8e54a', // yellow — #2
  '3': '#ff9f3a', // orange — #3
  '.': '#ff4d4d', // red — not in 3-pack
};

const LABELS = {
  '1': '1',
  '2': '2',
  '3': '3',
  '.': '—',
};

// Cells use dark fill text for high-contrast labels on lime/yellow/orange,
// white text on the red (not-in-pack) cells for legibility.
const LABEL_FILL = {
  '1': '#0a0a0a',
  '2': '#0a0a0a',
  '3': '#0a0a0a',
  '.': '#ffffff',
};

// ── Geometry ────────────────────────────────────────────────────────

const WIDTH = 1200;
const HEIGHT = 500;
const CELL = 34;
const GAP = 3;
const GRID_SIZE = 9 * CELL + 8 * GAP; // 306 + 24 = 330
const GRID_X = WIDTH - GRID_SIZE - 80; // 80px right margin
const GRID_Y = Math.round((HEIGHT - GRID_SIZE) / 2); // 85

// ── Font embedding ──────────────────────────────────────────────────

const fontBuf = readFileSync(FONT_PATH);
const fontB64 = fontBuf.toString('base64');

// ── Heatmap cells ───────────────────────────────────────────────────

function buildCells() {
  const out = [];
  for (let y = 0; y < 9; y++) {
    const row = PATTERN[y];
    for (let x = 0; x < 9; x++) {
      const ch = row[x] ?? '.';
      const cx = GRID_X + x * (CELL + GAP);
      const cy = GRID_Y + y * (CELL + GAP);
      const fill = COLORS[ch];
      const label = LABELS[ch];
      const labelFill = LABEL_FILL[ch];
      out.push(`    <rect x="${cx}" y="${cy}" width="${CELL}" height="${CELL}" rx="5" fill="${fill}"/>
    <text x="${cx + CELL / 2}" y="${cy + CELL / 2 + 5}" font-family="Bricolage Grotesque" font-size="15" font-weight="700" fill="${labelFill}" text-anchor="middle">${label}</text>`);
    }
  }
  return out.join('\n');
}

// ── SVG template ────────────────────────────────────────────────────

const svg = `<svg width="${WIDTH}" height="${HEIGHT}" viewBox="0 0 ${WIDTH} ${HEIGHT}" xmlns="http://www.w3.org/2000/svg">
  <!--
    TurfMap Shorby banner — ${WIDTH}×${HEIGHT}.
    Auto-generated by scripts/generate-shorby-banner.mjs.
    DO NOT edit by hand — re-run the script.

    Mirrors the Local Lead Machine banner orientation:
      - Brand lockup on the left (icon + "TurfMap" wordmark in
        Bricolage Grotesque + sub-line)
      - Product visual on the right (the SAME 9×9 hero heatmap
        rendered on the homepage, same PATTERN, same rank colors)
      - Italic tagline bottom-right ("GOOGLE MAPS AUDIT TOOL")
  -->
  <defs>
    <!-- Embed Bricolage Grotesque Bold as a base64 data URI so the
         PNG export reproduces the site wordmark faithfully without
         relying on system font availability. -->
    <style type="text/css"><![CDATA[
      @font-face {
        font-family: 'Bricolage Grotesque';
        font-style: normal;
        font-weight: 700;
        src: url(data:font/ttf;base64,${fontB64}) format('truetype');
      }
    ]]></style>
    <linearGradient id="bg-grad" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0%" stop-color="#0d0d10"/>
      <stop offset="100%" stop-color="#070708"/>
    </linearGradient>
    <radialGradient id="lime-glow" cx="22%" cy="38%" r="55%">
      <stop offset="0%" stop-color="#c5ff3a" stop-opacity="0.08"/>
      <stop offset="60%" stop-color="#c5ff3a" stop-opacity="0.02"/>
      <stop offset="100%" stop-color="#c5ff3a" stop-opacity="0"/>
    </radialGradient>
  </defs>

  <!-- Background -->
  <rect width="${WIDTH}" height="${HEIGHT}" fill="url(#bg-grad)"/>
  <rect width="${WIDTH}" height="${HEIGHT}" fill="url(#lime-glow)"/>
  <rect x="0.5" y="0.5" width="${WIDTH - 1}" height="${HEIGHT - 1}" fill="none" stroke="#27272a" stroke-width="1"/>

  <!-- ── LEFT: brand lockup ────────────────────────────────────── -->

  <!-- Lime icon square with crosshair (mirrors public/brand/turfmap-icon.svg) -->
  <g transform="translate(80, 190)">
    <rect width="120" height="120" rx="22" fill="#c5ff3a"/>
    <circle cx="60" cy="60" r="28" fill="#000"/>
    <circle cx="60" cy="60" r="22" fill="#c5ff3a"/>
    <rect x="56.5" y="22" width="7"  height="14" rx="3.5" fill="#000"/>
    <rect x="56.5" y="84" width="7"  height="14" rx="3.5" fill="#000"/>
    <rect x="22"   y="56.5" width="14" height="7" rx="3.5" fill="#000"/>
    <rect x="84"   y="56.5" width="14" height="7" rx="3.5" fill="#000"/>
    <circle cx="60" cy="60" r="4" fill="#000"/>
  </g>

  <!-- "TurfMap" wordmark in Bricolage Grotesque Bold, with a small
       lime ™ superscript — matches the live MarketingNav. -->
  <text x="230" y="278"
        font-family="Bricolage Grotesque"
        font-size="96" font-weight="700"
        letter-spacing="-3" fill="#fafafa">TurfMap</text>
  <text x="654" y="208"
        font-family="Bricolage Grotesque"
        font-size="28" font-weight="700"
        fill="#c5ff3a">™</text>

  <!-- Sub-line — mirrors the reference's supporting line + ties the
       banner to the product positioning. -->
  <text x="232" y="320"
        font-family="Bricolage Grotesque"
        font-size="17" font-weight="700"
        letter-spacing="3" fill="#a1a1aa">81-POINT GEO-GRID · RANK BY CELL</text>

  <!-- ── RIGHT: 9×9 heatmap (same PATTERN as the homepage hero) ── -->
  <g>
${buildCells()}
  </g>

  <!-- ── Bottom-right tagline ──────────────────────────────────── -->
  <text x="${WIDTH - 80}" y="${HEIGHT - 45}"
        font-family="Bricolage Grotesque"
        font-size="22" font-weight="700"
        font-style="italic"
        fill="#c5ff3a"
        text-anchor="end"
        letter-spacing="1.5">GOOGLE MAPS AUDIT TOOL</text>
</svg>
`;

writeFileSync(OUT_SVG, svg);
console.log(`✓ wrote ${OUT_SVG} (${svg.length} bytes)`);

// ── PNG export at 1x and 2x ────────────────────────────────────────

const svgBuf = Buffer.from(svg, 'utf8');

await sharp(svgBuf, { density: 144 })
  .resize(WIDTH, HEIGHT)
  .png()
  .toFile(OUT_PNG_1X);
const info1x = await sharp(OUT_PNG_1X).metadata();
console.log(`✓ wrote ${OUT_PNG_1X} (${info1x.width}×${info1x.height})`);

await sharp(svgBuf, { density: 288 })
  .resize(WIDTH * 2, HEIGHT * 2)
  .png()
  .toFile(OUT_PNG_2X);
const info2x = await sharp(OUT_PNG_2X).metadata();
console.log(`✓ wrote ${OUT_PNG_2X} (${info2x.width}×${info2x.height})`);
